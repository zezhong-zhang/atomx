"""Hydrogenic self-energy function ``F(Zα)`` — FAC/Indelicato–Mohr tabulation.

This table is the *authoritative* hydrogenic self-energy function for the
point-nucleus Coulomb problem (plus FAC's tabulated finite-Fermi-radius
correction).  It replaces an earlier table whose values agreed with the
published function only at ``Z = 1`` and diverged with the wrong
``Z``-dependence thereafter — by 2.5x at ``Z = 10`` and 14.7x at ``Z = 92``.
See ``docs/archive/2026-09/PHYSICS_NUMERICS_REVIEW_2026-09-19.md`` finding C2.

Citations
---------
- P. J. Mohr, Phys. Rev. A 26, 2338 (1982); Phys. Rev. A 46, 4421 (1992).
- P. Indelicato and P. J. Mohr, Theor. Chim. Acta 80, 207 (1991);
  Phys. Rev. A 46, 172 (1992).
- V. A. Yerokhin and V. M. Shabaev, J. Phys. Chem. Ref. Data 44, 033103
  (2015) — used to validate the ``Z``-dependence independently.
- Values transcribed from FAC 1.1.x ``faclib/coulomb.c`` static arrays
  ``_qed_za``, ``_qed_se0``, ``_qed_se1``, ``_zd``, ``_sd`` and ``_bethe``
  (programmatically, not by hand).

Units and normalisation
-----------------------
``F`` is dimensionless and the self-energy of a point-nucleus hydrogenic
one-electron orbital with principal quantum number ``n`` and Dirac quantum
number ``kappa`` is

    ``E_SE = (α / π n³) · (Zα)⁴ · F(Zα) · m_e c²``

with ``α`` the fine-structure constant.  In Hartree units ``m_e c² = 1/α²``,
so ``E_SE = (Zα)⁴ F / (π α n³)`` — the same prefactor FAC uses
(``c = (Zα)⁴/(π n³ α); r0 = r * c``).

Coverage
--------
* ``TABLE``: ``1s1/2``, ``2s1/2``, ``2p1/2``, ``2p3/2`` on the fine
  ``Z_GRID`` (1…120, from FAC ``_qed_se0 + _qed_se1``).
* ``SD_TABLE``: every ``n <= 5`` orbital with ``|kappa| <= 3`` on the
  coarser ``SD_Z_GRID`` (from FAC ``_sd``), which carries the full
  ``l``/``j`` dependence the old table discarded.
* ``BETHE_LOG`` + :func:`klamaq_f`: FAC's analytic Bethe-logarithm form,
  the fallback for ``n > 5`` (the old code used ``F(1s)/n³``, which has
  the wrong ``l`` dependence entirely).
"""

