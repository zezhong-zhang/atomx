"""FAC parity tests for the DR driver (HYP-146, HYP-530).

The acceptance gate is ``|α_atomx - α_FAC| / α_FAC ≤ 0.20`` at four electron
temperatures (1, 5, 10, 50 MK) for Fe XVII → Fe XVI dielectronic recombination,
Δn=0 + Δn=1 channels combined.  The FAC reference is regenerated by
``benchmarks/bench_fac_dr.py``; the JSON fixture at ``tests/data/fe17_dr_fac.json``
captures every FAC resonance (E, J, Γ_A, A_r) so the parity tests run without
``sfac`` installed.

Three tests live here:

1. ``test_kernel_parity_with_fac`` — feed FAC's own AI rates, TR rates, and
   resonance energies into atomx's ``dr_rate_coefficient`` Burgess kernel and
   verify it reproduces the FAC reference α_DR within 1 % at every gate
   temperature.  This is the test that *actually* protects the DR kernel.

2. ``test_end_to_end_driver_returns_positive_alpha`` — smoke test that always
   runs with the placeholder hydrogenic widths.

3. ``test_end_to_end_gate_20pct`` — exercises the public end-to-end driver
   ``dr_calculate`` against a solved Fe XVII atom using the HYP-530
   ab-initio Auger hook (``make_abinitio_auger_rate_fn``).  The 20 % gate
   is marked ``pytest.xfail`` because the per-pair Auger rate from
   ``auger_rate_csf_average`` over-counts magnetic substates vs the
   J-resolved FAC value by 1.2-15x depending on J and channel (see the
   5-resonance panel in ``test_auger_kll_vs_fac.py``).  Closing the gate
   needs the Cowan-Grant 6j-based J-resolved Auger angular coefficient —
   the remaining gap on HYP-530.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from atomx import Atom
from atomx.scattering.autoionization import (
    AutoionizationState,
    dr_calculate,
    dr_rate_coefficient,
)
from atomx.scattering.dielectronic_recombination import make_abinitio_auger_rate_fn


FIXTURE_PATH = Path(__file__).parent / "data" / "fe17_dr_fac.json"
GATE_TOLERANCE = 0.20  # 20 % rms per HYP-146 acceptance criteria
KERNEL_TOLERANCE = 0.01  # 1 % parity for the Burgess kernel itself


@pytest.fixture(scope="module")
def fac_fixture() -> dict:
    if not FIXTURE_PATH.exists():
        pytest.skip(f"FAC reference fixture missing: {FIXTURE_PATH}")
    data = json.loads(FIXTURE_PATH.read_text())
    if data.get("n_fac_resonances", 0) == 0:
        pytest.skip("FAC fixture has zero resonances — regenerate with benchmarks/bench_fac_dr.py")
    return data


def _fac_resonance_states(data: dict) -> list[AutoionizationState]:
    return [
        AutoionizationState(
            label=row["label"],
            E_resonance_eV=float(row["E_resonance_eV"]),
            J=float(row["J"]),
            gamma_auger_per_s=float(row["gamma_auger_per_s"]),
            a_radiative_per_s=float(row["a_radiative_per_s"]),
        )
        for row in data["resonances"]
    ]


# ---------------------------------------------------------------------------
# 1.  Kernel parity — feeds FAC widths through atomx's Burgess kernel
# ---------------------------------------------------------------------------

def test_kernel_parity_with_fac(fac_fixture):
    states = _fac_resonance_states(fac_fixture)
    T_eV = np.asarray(fac_fixture["T_eV"], dtype=float)
    rc = dr_rate_coefficient(
        states,
        T_eV,
        initial_state_g=fac_fixture.get("initial_state_g", 1.0),
        initial_state_label="Fe XVII 2p6 J=0 (FAC reference)",
    )
    expected = np.asarray(fac_fixture["alpha_fac_cm3_s"], dtype=float)
    np.testing.assert_allclose(
        rc.alpha_cm3_s, expected, rtol=KERNEL_TOLERANCE,
        err_msg=(
            "atomx Burgess kernel disagrees with FAC AITable+TRTable combine "
            "above 1 % — investigate dr_rate_coefficient prefactor or units."
        ),
    )


# ---------------------------------------------------------------------------
# 2.  End-to-end driver — exercises the 20 % gate
# ---------------------------------------------------------------------------

# Atom-like input matching ``benchmarks/bench_fac_dr.py``.  Inlined here so the
# test does not import from the benchmarks tree.
class _FeXVIIModel:
    Z = 26
    charge = 16
    converged = True
    _config_strings = ["1s2 2s2 2p6"]
    result = None
    orbital_energies = {
        "1s1/2": -260.0,
        "2s1/2": -47.0,
        "2p1/2": -45.0,
        "2p3/2": -44.6,
        "3s1/2": -18.0,
        "3p1/2": -16.0,
        "3p3/2": -15.8,
        "3d3/2": -14.4,
        "3d5/2": -14.4,
        "4s1/2": -10.0,
        "4p1/2": -9.5,
        "4p3/2": -9.4,
        "4d3/2": -9.0,
        "4d5/2": -9.0,
    }


@pytest.fixture(scope="module")
def solved_fe17_atom():
    """Real MCDHF Fe XVII solve with 2p^5 3l reference configs.

    Provides the radial orbitals + B-spline workspace that
    ``make_abinitio_auger_rate_fn`` closes over.  Matches the solve in
    ``tests/test_auger_kll_vs_fac.py::fe17_result`` so the two tests share
    calibration assumptions.
    """
    atom = Atom(
        Z=26,
        charge=16,
        configs=[
            "1s2 2s2 2p6",
            "1s2 2s2 2p5 3s1",
            "1s2 2s2 2p5 3p1",
            "1s2 2s2 2p5 3d1",
        ],
        j_resolved_csfs=False,
        breit=False,
        qed=False,
    )
    atom.solve()
    return atom


def test_end_to_end_driver_returns_positive_alpha(fac_fixture):
    """Smoke test: dr_calculate produces finite positive α with external hooks."""
    T_eV = np.asarray(fac_fixture["T_eV"], dtype=float)
    # Provide simple positive width hooks so the driver does not need to build
    # an MCDHF result for this smoke test.
    rc = dr_calculate(
        _FeXVIIModel(),
        "1s2 2s2 2p6",
        n_max=4,
        l_max=2,
        T_eV=T_eV,
        auger_rate_fn=lambda _spec, _e: 1e13,
        radiative_rate_fn=lambda _spec, _e: 1e10,
    )
    assert rc.alpha_cm3_s.shape == T_eV.shape
    assert np.all(rc.alpha_cm3_s > 0.0), "expected α_DR > 0 at every gate T_e"
    assert len(rc.resonances) > 0, "enumeration should produce resonances"


@pytest.mark.xfail(
    reason=(
        "20% FAC parity gate still open. Both ab-initio hooks are wired — "
        "make_abinitio_auger_rate_fn and make_abinitio_radiative_rate_fn "
        "(the latter auto-applied by dr_calculate) — over a solved Fe XVII "
        "atom, but α_DR still overshoots FAC by ~162x/3.4x/1.7x/1.9x at "
        "T_MK = 1/5/10/50. Residual gap is likely the J-resolved "
        "(Cowan-Grant 6j) Auger angular coefficient (currently the "
        "average-of-configuration factor over-counts magnetic substates) "
        "and/or incomplete radiative stabilisation channels."
    ),
    strict=False,
)
def test_end_to_end_gate_20pct(fac_fixture, solved_fe17_atom):
    """Acceptance gate: |Δα/α_FAC| ≤ 0.20 at T_e ∈ {1, 5, 10, 50} MK."""
    T_eV = np.asarray(fac_fixture["T_eV"], dtype=float)
    expected = np.asarray(fac_fixture["alpha_fac_cm3_s"], dtype=float)
    auger_fn = make_abinitio_auger_rate_fn(solved_fe17_atom)
    rc = dr_calculate(
        solved_fe17_atom,
        "1s2 2s2 2p6 3s1",
        n_max=4,
        l_max=2,
        T_eV=T_eV,
        auger_rate_fn=auger_fn,
    )
    rel = np.abs(rc.alpha_cm3_s - expected) / expected
    print(
        "\nDR gate panel (solved Fe XVII + ab-initio Auger hook):\n"
        f"  T_MK  = {fac_fixture['T_MK']}\n"
        f"  atomx = {rc.alpha_cm3_s.tolist()}\n"
        f"  FAC   = {expected.tolist()}\n"
        f"  |Δα|/α = {rel.tolist()}"
    )
    assert np.all(rel <= GATE_TOLERANCE), (
        f"|Δα/α_FAC| = {rel.tolist()} exceeds {GATE_TOLERANCE:.0%} at "
        f"T_MK={fac_fixture['T_MK']}; atomx={rc.alpha_cm3_s.tolist()} vs "
        f"FAC={expected.tolist()}"
    )
