const { chromium } = require('/home/zzhang/.local/share/atomx-nist-atlas/browser-check/node_modules/playwright');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:'/home/zzhang/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const response=await page.goto(process.argv[2]||'http://127.0.0.1:8877');
  await page.waitForSelector('.model');
  if(await page.locator('.element').count()!==118)throw Error('element coverage');
  if(await page.locator('.model tbody tr').count()!==8)throw Error('Yb matched records');
  await page.screenshot({path:__dirname+'/desktop.png',fullPage:true});
  await page.locator('[data-tab="levels"]').click();
  await page.waitForFunction(()=>document.querySelector('#page-label').textContent.includes('349'));
  if(await page.locator('#content tbody tr').count()!==75)throw Error('level pagination');
  await page.locator('#next').click();
  if(!(await page.locator('#page-label').textContent()).includes('2 /'))throw Error('next page');
  await page.locator('[data-tab="sources"]').click();
  if(!(await page.locator('#content').textContent()).includes('SHA256'))throw Error('source binding');
  await page.locator('[data-z="10"]').click();
  await page.waitForFunction(()=>document.querySelector('#ion-info').textContent.startsWith('Ne I'));
  await page.locator('[data-tab="lines"]').click();
  await page.waitForFunction(()=>document.querySelector('#content').textContent.includes('实测 nm'));
  await page.locator('#kind').selectOption('observed');
  if(await page.locator('#content tbody tr').count()===0)throw Error('Ne observed coverage');
  await page.locator('#search').fill('Yb');
  if(await page.locator('.element:not(.dim)').count()!==1)throw Error('element filtering');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#search').fill('');
  await page.locator('[data-z="118"]').scrollIntoViewIfNeeded();
  await page.locator('[data-z="118"]').click();
  await page.waitForFunction(()=>document.querySelector('#title').textContent.startsWith('Og'));
  await page.locator('[data-tab="models"]').click();
  await page.waitForFunction(()=>document.querySelector('#content').textContent.includes('没有接入'));
  await page.screenshot({path:__dirname+'/mobile.png',fullPage:true});
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(__dirname+'/browser_result.json',JSON.stringify({passed:true,http_status:response.status(),elements:118,yb_matched_rows:8,pagination:true,observed_filter:true,source_hashes_visible:true,element_search:true,mobile_empty_state:true,javascript_errors:errors},null,2));
  await browser.close();
  process.stdout.write('Browser checks passed\n');
})().catch(e=>{process.stderr.write(e.stack+'\n');process.exit(1)});
