        def do_POST(self):
            parsed = urlparse(self.path)
            if parsed.path != "/api/compare-upload":
                self.send_json({"error": "not found"}, 404)
                return
            try:
                query = parse_qs(parsed.query)
                z = int(query.get("z", ["1"])[0])
                charge = int(query.get("charge", ["0"])[0])
                basis = query.get("basis", ["observed"])[0]
                length = int(self.headers.get("Content-Length", "0"))
                if not 1 <= z <= 118 or not 0 <= charge < z:
                    raise ValueError("invalid atomic number or charge")
                if not 0 < length <= 5_000_000:
                    raise ValueError("CSV must be between 1 byte and 5 MB")
                content = self.rfile.read(length).decode("utf-8-sig")
                with sqlite3.connect(dbpath) as db:
                    db.row_factory = sqlite3.Row
                    result = compare_uploaded_lines(db, z, charge, basis, content)
                self.send_json(result)
            except (ValueError, UnicodeDecodeError) as exc:
                self.send_json({"error": str(exc)}, 400)

