"""Generate the benchmark performance dashboard.

The dashboard is intentionally CSV-driven: benchmark scripts own the
measurements, while this script only summarizes committed result files into a
stable markdown table for review and CI/pre-commit freshness checks.
"""

from __future__ import annotations

import argparse
import csv
import sys
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BENCHMARKS = ROOT / "benchmarks"
DEFAULT_OUT = BENCHMARKS / "PERFORMANCE.md"


@dataclass(frozen=True)
class PerfRow:
    Z: str
    iso: str
    method: str
    wall_time_s: float | None
    reference_time_s: float | None = None
    metric: str = ""


def _fmt(value: float | None) -> str:
    if value is None:
        return "-"
    if value == 0:
        return "0.000"
    if abs(value) < 0.001:
        return f"{value:.3e}"
    return f"{value:.3f}"


def _read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def _float(row: dict[str, str], key: str) -> float | None:
    try:
        raw = row.get(key, "")
        if raw == "":
            return None
        return float(raw)
    except ValueError:
        return None


def _matrix_rows() -> list[PerfRow]:
    rows: list[PerfRow] = []
    for row in _read_csv(BENCHMARKS / "results_fac_matrix.csv"):
        rows.append(
            PerfRow(
                Z=row.get("Z", ""),
                iso=row.get("iso", ""),
                method="FAC matrix / atomx",
                wall_time_s=_float(row, "t_atomx"),
                reference_time_s=_float(row, "t_sfac"),
                metric=f"E1 A={row.get('atomx_first_A_s', '-')}",
            )
        )
    return rows


def _fe_panel_rows() -> list[PerfRow]:
    rows: list[PerfRow] = []
    for row in _read_csv(BENCHMARKS / "results_fac_fe_panel.csv"):
        ion = row.get("ion", "")
        charge = row.get("charge", "")
        rows.append(
            PerfRow(
                Z="26",
                iso=ion or f"Fe {charge}",
                method="Fe panel / structure",
                wall_time_s=None,
                reference_time_s=None,
                metric=f"levels={row.get('n_levels', '-')}, E1={row.get('n_e1', '-')}",
            )
        )
    return rows


def _crm_rows() -> list[PerfRow]:
    rows: list[PerfRow] = []
    for csv_path in sorted(BENCHMARKS.glob("results_fac_crm_*.csv")):
        target = csv_path.stem.removeprefix("results_fac_crm_")
        records = _read_csv(csv_path)
        balance = [r for r in records if r.get("kind") == "balance"]
        if not balance:
            continue
        first = balance[0]
        rows.append(
            PerfRow(
                Z=target,
                iso=f"{target} CRM",
                method="CRM balance",
                wall_time_s=None,
                reference_time_s=None,
                metric=f"Te={first.get('Te_eV', '-')} eV, ions={len(balance)}",
            )
        )
    return rows


def collect_rows() -> list[PerfRow]:
    rows: list[PerfRow] = []
    rows.extend(_matrix_rows())
    rows.extend(_fe_panel_rows())
    rows.extend(_crm_rows())
    return rows


def render_markdown(rows: list[PerfRow]) -> str:
    lines = [
        "# AtomX Benchmark Performance",
        "",
        "Generated by `scripts/perf_dashboard.py` from committed benchmark CSVs.",
        "",
        "| Z | Iso / target | Method | atomx time (s) | reference time (s) | Metric |",
        "|---:|---|---|---:|---:|---|",
    ]
    for row in rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    row.Z,
                    row.iso,
                    row.method,
                    _fmt(row.wall_time_s),
                    _fmt(row.reference_time_s),
                    row.metric,
                ]
            )
            + " |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="fail if the dashboard is stale")
    args = parser.parse_args(argv)

    content = render_markdown(collect_rows())
    if args.check:
        existing = args.out.read_text() if args.out.exists() else ""
        if existing != content:
            print(f"{args.out} is stale; run `python scripts/perf_dashboard.py`", file=sys.stderr)
            return 1
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
